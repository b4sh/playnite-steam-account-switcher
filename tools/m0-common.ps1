# Shared helpers for the M0 tools (dot-sourced by m0-inspect.ps1 and m0-switch.ps1).
# Everything here is read-only except Add-ResultsText, which only appends to the results file.

$SteamId64Base = [UInt64]76561197960265728
$SteamKey = 'HKCU:\Software\Valve\Steam'
$ActiveProcessKey = 'HKCU:\Software\Valve\Steam\ActiveProcess'

function Get-RegValue([string]$path, [string]$name) {
    # Returns @{ Exists; Kind; Value } without modifying anything.
    $key = Get-Item -LiteralPath $path -ErrorAction SilentlyContinue
    if (-not $key) { return @{ Exists = $false; Kind = 'key missing'; Value = $null } }
    if ($key.GetValueNames() -notcontains $name) { return @{ Exists = $false; Kind = 'missing'; Value = $null } }
    return @{
        Exists = $true
        Kind   = $key.GetValueKind($name).ToString()
        Value  = $key.GetValue($name, $null, 'DoNotExpandEnvironmentNames')
    }
}

function Get-DwordValue($rv) {
    if (-not $rv.Exists -or $rv.Kind -ne 'DWord') { return $null }
    return [BitConverter]::ToUInt32([BitConverter]::GetBytes([int32]$rv.Value), 0)
}

function ConvertFrom-TextVdf([string]$text) {
    # Minimal text-VDF reader: quoted strings, braces, // comments. Duplicate keys: last wins.
    $root = [ordered]@{}
    $stack = New-Object System.Collections.Stack
    $current = $root
    $pendingKey = $null
    foreach ($m in [regex]::Matches($text, '"((?:[^"\\]|\\.)*)"|[{}]|//[^\n]*')) {
        $t = $m.Value
        if ($t.StartsWith('//')) { continue }
        if ($t -eq '{') {
            $child = [ordered]@{}
            $current[$pendingKey] = $child
            $stack.Push($current)
            $current = $child
            $pendingKey = $null
        }
        elseif ($t -eq '}') {
            if ($stack.Count -gt 0) { $current = $stack.Pop() }
            $pendingKey = $null
        }
        else {
            $s = $m.Groups[1].Value -replace '\\(.)', '$1'
            if ($null -eq $pendingKey) { $pendingKey = $s }
            else { $current[$pendingKey] = $s; $pendingKey = $null }
        }
    }
    return $root
}

function Resolve-SteamPath([string]$override) {
    if ($override) { return $override -replace '/', '\' }
    foreach ($src in @(@($SteamKey, 'SteamPath'), @('HKLM:\SOFTWARE\WOW6432Node\Valve\Steam', 'InstallPath'))) {
        $rv = Get-RegValue $src[0] $src[1]
        if ($rv.Exists -and $rv.Value) { return ([string]$rv.Value) -replace '/', '\' }
    }
    return $null
}

function Read-LoginUsers([string]$steamPath) {
    # Returns one object per account in loginusers.vdf (no secrets are stored in this file).
    $path = Join-Path $steamPath 'config\loginusers.vdf'
    if (-not (Test-Path -LiteralPath $path)) { return @() }
    $vdf = ConvertFrom-TextVdf ([IO.File]::ReadAllText($path, [Text.Encoding]::UTF8))
    $users = $vdf['users']
    if (-not $users) { return @() }
    foreach ($sid in $users.Keys) {
        $u = $users[$sid]
        $id64 = [UInt64]0
        $accountId = $null
        if ([UInt64]::TryParse($sid, [ref]$id64) -and $id64 -ge $SteamId64Base) { $accountId = $id64 - $SteamId64Base }
        [pscustomobject]@{
            SteamId64        = $sid
            AccountId        = $accountId
            AccountName      = $u['AccountName']
            PersonaName      = $u['PersonaName']
            RememberPassword = $u['RememberPassword']
            AutoLogin        = $u['AutoLogin']
        }
    }
}

function Get-SteamProcessState {
    # Steam counts as running when ActiveProcess\pid points to a live steam.exe (SPEC §5.3);
    # any other steam.exe process is reported too.
    $pid_ = Get-DwordValue (Get-RegValue $ActiveProcessKey 'pid')
    $pidAlive = $false
    if ($pid_) {
        $p = Get-Process -Id ([int]$pid_) -ErrorAction SilentlyContinue
        $pidAlive = [bool]($p -and $p.ProcessName -ieq 'steam')
    }
    $all = @(Get-Process -Name steam -ErrorAction SilentlyContinue | ForEach-Object { $_.Id } | Sort-Object)
    [pscustomobject]@{
        Pid        = $pid_
        PidAlive   = $pidAlive
        SteamPids  = $all
        AnyRunning = $pidAlive -or $all.Count -gt 0
    }
}

function Add-ResultsText([string]$resultsPath, [string]$text) {
    $utf8 = New-Object System.Text.UTF8Encoding($false)
    if (-not (Test-Path -LiteralPath $resultsPath)) {
        [IO.File]::WriteAllText($resultsPath, "# M0 results`r`n`r`nGenerated by the scripts in ``tools/``. See SPEC.md §5 and §10.`r`n`r`n", $utf8)
    }
    [IO.File]::AppendAllText($resultsPath, $text, $utf8)
}
